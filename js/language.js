  function applyLanguage(language) {
    const lang = translations[language] ? language : "en";
    const t = translations[lang];
    const setHTML = (selector, value) => {
      const element = document.querySelector(selector);
      if (element) element.innerHTML = value;
    };
    const setText = (selector, value) => {
      const element = document.querySelector(selector);
      if (element) element.textContent = value;
    };
    const setMany = (selector, values, render) => {
      document.querySelectorAll(selector).forEach((element, index) => {
        if (values[index] !== undefined) render(element, values[index], index);
      });
    };

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.title = lang === "ar"
      ? "GBTCcoin — منظومة سيولة مترابطة"
      : lang === "fr"
        ? "GBTCcoin — Écosystème de liquidité connecté"
        : lang === "es"
          ? "GBTCcoin — Ecosistema de liquidez conectado"
          : lang === "de"
            ? "GBTCcoin — Vernetztes Liquiditätsökosystem"
            : lang === "tr"
              ? "GBTCcoin — Bağlantılı Likidite Ekosistemi"
              : lang === "zh"
                ? "GBTCcoin — 互联流动性生态系统"
                : lang === "ru"
                  ? "GBTCcoin — Связанная экосистема ликвидности"
                  : "GBTCcoin — Connected Liquidity Ecosystem";

    setMany(".main-nav a", t.nav, (el, value) => el.textContent = value);
    setHTML(".header-button", `${t.explore} <span>↗</span>`);
    setText(".eyebrow", t.eyebrow);
    setHTML(".hero h1", t.heroTitle);
    setText(".hero-description", t.heroDescription);
    setHTML(".hero-actions .button-primary", `${t.discover} <span>↗</span>`);
    setText(".hero-actions .button-secondary", t.visionButton);
    setText(".hero-note", t.heroNote);
    setText(".visual-caption", t.visualCaption);
    setText(".ticker > div", t.ticker);

    setText(".intro-section .section-label", t.visionLabel);
    setHTML(".intro-grid h2", t.visionTitle);
    setMany(".intro-grid .section-copy", t.visionParagraphs, (el, value) => el.textContent = value);

    setText(".ecosystem-section > .section-heading .section-label", t.ecosystemLabel);
    setHTML(".ecosystem-section .section-heading h2", t.ecosystemTitle);
    setText(".ecosystem-section .section-heading p", t.ecosystemDescription);
    setMany(".feature-card", t.cards, (card, value) => {
      const heading = card.querySelector("h3");
      const paragraph = card.querySelector("p");
      const link = card.querySelector(".card-link");
      if (heading) heading.textContent = value[0];
      if (paragraph) paragraph.textContent = value[1];
      if (link) link.innerHTML = `${value[2]} <span>↗</span>`;
    });

    setText(".utility-section .section-label", t.futureLabel);
    setHTML(".utility-grid h2", t.futureTitle);
    setText(".utility-grid .section-copy", t.futureDescription);
    setMany(".utility-item", t.utilities, (item, value) => {
      const spans = item.querySelectorAll("span");
      if (spans[1]) spans[1].textContent = value;
    });
    setText(".notice", t.notice);

    setText(".roadmap-section > .section-label", t.roadmapLabel);
    setHTML(".roadmap-section .section-heading h2", t.roadmapTitle);
    setText(".roadmap-section .section-heading p", t.roadmapDescription);
    setMany(".roadmap-item", t.phases, (item, value) => {
      const heading = item.querySelector("h3");
      const paragraph = item.querySelector("p");
      const status = item.querySelector(".phase-status");
      if (heading) heading.textContent = value[0];
      if (paragraph) paragraph.textContent = value[1];
      if (status) status.textContent = value[2];
    });

    setText(".closing-section .section-label", t.closingLabel);
    setHTML(".closing-section h2", t.closingTitle);
    setText(".closing-section p", t.closingDescription);
    setText(".closing-section .button", t.backTop);
    setText(".site-footer > p", t.footerDescription);

    const footerCopy = document.querySelector(".footer-copy");
    if (footerCopy) {
      footerCopy.innerHTML = `© <span id="year">${new Date().getFullYear()}</span> GBTCcoin. ${t.footerRights}`;
    }

    const switcher = document.getElementById("language-switcher");
    if (switcher) switcher.value = lang;
    try {
      localStorage.setItem("hbtc-language", lang);
    } catch (_) {}
  }

  document.addEventListener("DOMContentLoaded", () => {
    const switcher = document.getElementById("language-switcher");
    let preferred = "en";
    try {
      preferred = localStorage.getItem("hbtc-language") ||
        ((navigator.language || "").toLowerCase().startsWith("ar") ? "ar" : (navigator.language || "").toLowerCase().startsWith("fr") ? "fr" : (navigator.language || "").toLowerCase().startsWith("es") ? "es" : (navigator.language || "").toLowerCase().startsWith("de") ? "de" : (navigator.language || "").toLowerCase().startsWith("tr") ? "tr" : (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : (navigator.language || "").toLowerCase().startsWith("ru") ? "ru" : "en");
    } catch (_) {
      preferred = (navigator.language || "").toLowerCase().startsWith("ar") ? "ar" : (navigator.language || "").toLowerCase().startsWith("es") ? "es" : (navigator.language || "").toLowerCase().startsWith("de") ? "de" : (navigator.language || "").toLowerCase().startsWith("tr") ? "tr" : (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : (navigator.language || "").toLowerCase().startsWith("ru") ? "ru" : "en";
    }

    applyLanguage(preferred);
    if (switcher) switcher.addEventListener("change", () => applyLanguage(switcher.value));
  });

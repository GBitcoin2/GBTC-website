  function detectPreferredLanguage() {
    const deviceLanguages = Array.isArray(navigator.languages)
      ? navigator.languages
      : [];

    const candidates = [...deviceLanguages, navigator.language];

    for (const candidate of candidates) {
      const baseLanguage = String(candidate || "")
        .trim()
        .toLowerCase()
        .split(/[-_]/)[0];

      if (translations[baseLanguage]) return baseLanguage;
    }

    try {
      const saved = localStorage.getItem("hbtc-language");
      if (saved && translations[saved]) return saved;
    } catch (_) {}

    return "en";
  }

  document.addEventListener("DOMContentLoaded", () => {
    const switcher = document.getElementById("language-switcher");
    const preferred = detectPreferredLanguage();

    applyLanguage(preferred, false);

    if (switcher) {
      switcher.addEventListener("change", () => {
        applyLanguage(switcher.value, true);
      });
    }
  });

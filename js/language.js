  function normalizeCard(value) {
    if (Array.isArray(value)) {
      return {
        title: value[0] || "",
        description: value[1] || "",
        label: value[2] || ""
      };
    }
    return {
      title: value.title || "",
      description: value.description || "",
      label: value.label || value.tag || ""
    };
  }

  function normalizePhase(value) {
    if (Array.isArray(value)) {
      return {
        title: value[0] || "",
        description: value[1] || "",
        status: value[2] || "PLANNED"
      };
    }
    return {
      title: value.title || "",
      description: value.description || "",
      status: value.status || "PLANNED"
    };
  }

